for r in S.ORDER:
    cid=r["id"]; ch=cid
    out.append("")
    out.append(f"## ג”€ג”€ {r['name']} ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€ג”€")
    out.append(f"label expanded_route_{cid}:")
    out.append("    $ route_good = 0")
    out.append("    $ route_risky = 0")
    out.append("    $ route_heat = 0")
    out.append(f"    $ route_id = {q(cid)}")
    out.append(f"    scene bg {r['bg']}")
    out.append("    with fade")
