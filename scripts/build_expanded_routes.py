q=lambda s: json.dumps(s,ensure_ascii=False)

def lines(n, who, txt, ind=4):
    tag={"her":n,"mc":"mc","max":"max_rival","clara":"dorm","lady":"lady","dean":"dean","n":None}.get(who)
    pad = " " * ind
    if tag is None: return [f"{pad}{q(txt)}"]
    return [f"{pad}{tag} {q(txt)}"]

